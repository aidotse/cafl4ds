"""Offline clustering must cover every split and preserve future inference semantics."""

import json
import pickle
from pathlib import Path

import numpy as np
import pytest
import torch
from PIL import Image
from sklearn.metrics import adjusted_rand_score

from cafl4ds.offline_clustering import EMBED_DIM, discover_images, extract_embeddings, fit_clusters


def test_all_images_are_discovered_without_annotations(tmp_path: Path) -> None:
    """Missing driving attributes must not remove train, validation or test images."""
    for split in ("train", "val", "test"):
        directory = tmp_path / "images" / "100k" / split
        directory.mkdir(parents=True)
        for name in ("b.jpg", "a.jpg"):
            Image.new("RGB", (20, 10)).save(directory / name)
    records = discover_images(tmp_path)
    assert [row["split"] for row in records] == ["train", "train", "val", "val", "test", "test"]
    assert [Path(row["path"]).name for row in records] == ["a.jpg", "b.jpg"] * 3
    assert all(row["bytes"] > 0 for row in records)


def test_extraction_resume_and_cache_identity(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Resume avoids recomputation and rejects changed input files instead of misaligning IDs."""
    root, output = tmp_path / "bdd", tmp_path / "result"
    for split in ("train", "val", "test"):
        directory = root / "images" / "100k" / split
        directory.mkdir(parents=True)
        Image.new("RGB", (300, 200), color=(10, 30, 50)).save(directory / "image.jpg")

    class FakeEncoder:
        def __call__(self, images: torch.Tensor) -> torch.Tensor:
            return images.mean(dim=(1, 2, 3))[:, None].expand(-1, EMBED_DIM)

    monkeypatch.setattr("cafl4ds.offline_clustering.build_encoder", lambda _: FakeEncoder())
    manifest = extract_embeddings(root, output, device="cpu", batch_size=2, workers=0)
    saved = np.load(output / "embeddings.npy").copy()
    # Simulate an interrupted run: only the committed first row may be trusted.
    progress_path = output / "embedding_progress.json"
    progress = json.loads(progress_path.read_text())
    progress["completed"] = 1
    progress_path.write_text(json.dumps(progress))
    partial = np.load(output / "embeddings.npy", mmap_mode="r+")
    partial[1:] = np.nan
    partial.flush()
    extract_embeddings(root, output, device="cpu", batch_size=2, workers=0)
    np.testing.assert_array_equal(saved, np.load(output / "embeddings.npy"))
    monkeypatch.setattr("cafl4ds.offline_clustering.build_encoder", lambda _: pytest.fail("Cache was not reused"))
    assert extract_embeddings(root, output, device="cpu", workers=0)["fingerprint"] == manifest["fingerprint"]
    np.testing.assert_array_equal(saved, np.load(output / "embeddings.npy"))
    Image.new("RGB", (300, 200), color="red").save(root / "images/100k/test/image.jpg")
    with pytest.raises(ValueError, match="inputs changed"):
        extract_embeddings(root, output, device="cpu", workers=0)


def test_saved_pipeline_reproduces_probabilities_and_exemplars(tmp_path: Path) -> None:
    """Reloaded inference agrees with saved posteriors and separates known synthetic groups."""
    rng = np.random.default_rng(42)
    truth = np.repeat(np.arange(4), 50)
    centers = rng.normal(size=(4, EMBED_DIM)) * 3
    features = (centers[truth] + rng.normal(size=(len(truth), EMBED_DIM)) * 0.2).astype(np.float32)
    np.save(tmp_path / "embeddings.npy", features)
    records = [{"path": f"{i}.jpg", "split": ("train", "val", "test")[i % 3]} for i in range(len(truth))]
    (tmp_path / "manifest.json").write_text(json.dumps({"images": records, "fingerprint": "synthetic"}))
    (tmp_path / "embedding_progress.json").write_text(json.dumps({"completed": len(truth), "fingerprint": "synthetic"}))
    result = fit_clusters(tmp_path, pca_dim=8, n_init=2)
    with (tmp_path / "pca_gmm.pkl").open("rb") as stream:
        pipeline = pickle.load(stream)  # noqa: S301 - artifact generated by this test
    probabilities = np.load(tmp_path / "probabilities.npy")
    np.testing.assert_allclose(pipeline.predict_proba(features), probabilities, atol=1e-6)
    np.testing.assert_allclose(probabilities.sum(axis=1), 1, atol=1e-6)
    labels = np.load(tmp_path / "labels.npy")
    assert adjusted_rand_score(truth, labels) == pytest.approx(1)
    assert result["n_images"] == len(truth)
    assert result["gmm_converged"]
    assert sum(result["hard_cluster_counts"]) == len(truth)
    for entry in json.loads((tmp_path / "exemplars.json").read_text()):
        assert len(entry["central"]) == 6
        assert np.all(labels[entry["central"]] == entry["cluster"])
    (tmp_path / "embedding_progress.json").write_text(json.dumps({"completed": 2, "fingerprint": "synthetic"}))
    with pytest.raises(ValueError, match="Complete image embeddings"):
        fit_clusters(tmp_path, pca_dim=8)
